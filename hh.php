<?php
// Define a function to concatenate two strings
function concatenateStrings($str1, $str2) {
    // Concatenate the strings
    $result = $str1 . $str2;
    
    // Print the result
    echo $result;
}

// Example usage of the function
$string1 = "Hello, ";
$string2 = "World!";

// Call the function with the example strings
concatenateStrings($string1, $string2);
?>
